"""Generate the journal's main-experiment Hydra configs (3DC-Texture / 3DC-Mixed).

One table drives everything, so a condition is defined in exactly one place:

* ``CONDITIONS``: which non-shape features each condition uses (center-pixel
  ``hsv`` on/off, plus at most one texture feature) -- the leading columns of
  JOURNAL_EXPERIMENT_PLAN.md, Phase 5.
* ``TOLERANCES``: provisional per-texture-feature tolerance, written into the
  shared learning-module configs.
* ``CALIBRATED_TOLERANCES`` (Phase 4): when ``scripts/phase4_calibration.py``'s
  CSV exists, each eval experiment overrides its texture tolerance with the
  value calibrated on its own model (dataset x lighting), chosen under
  ``TOLERANCE_REGIME``. Rerun this script after Phase 4.

Writes (all overwritten on each run; hand-written configs are never touched):

* ``monty/sensor_module/journal/camera_surf_rgba_<texture or no_texture>.yaml``
  -- eval sensor modules emitting only their condition's texture feature, so
  per-step wall time is fair (Phase 6). Pretraining uses
  ``camera_surf_rgba_all_texture.yaml`` (hand-written, emits everything).
* ``monty/learning_module/journal/main/evidence_1lm_nn5_dod0025_<condition>.yaml``
* ``env_interface/journal/{train,eval}_3dc_{texture,mixed}.yaml`` (object lists
  read from the built datasets in ``$MONTY_DATA``)
* ``experiment/journal/pretrain_3dc_<dataset>_<lighting>_all_features.yaml``
* ``experiment/journal/eval_3dc_<dataset>_<lighting>_<condition>.yaml``

Usage::

    python scripts/generate_journal_configs.py
"""

from __future__ import annotations

import csv
import os
from pathlib import Path

import yaml

REPO = Path(__file__).parents[1]
CONF = REPO / "src" / "tbp" / "monty" / "conf"
DATA = Path(os.environ.get("MONTY_DATA", "~/tbp/data")).expanduser()

DATASETS = {"texture": "compat3d_texture", "mixed": "compat3d_mixed"}
LIGHTINGS = {"amb": "habitat_3dcompat_journal_surf_agent_amb",
             "dir": "habitat_3dcompat_journal_surf_agent_dir"}

#: condition -> (center-pixel hsv on?, texture feature or None)
CONDITIONS = {
    "shape_only": (False, None),
    "hsv": (True, None),
    "ltp": (False, "ltp"),
    "ltp_rgb": (False, "ltp_rgb"),
    "ltp_hsv": (False, "ltp_hsv"),
    "hsv_plus_ltp_rgb": (True, "ltp_rgb"),
    "hsv_plus_ltp_hsv": (True, "ltp_hsv"),
    "gabor": (False, "gabor"),
    "gabor_rgb": (False, "gabor_rgb"),
    "gabor_hsv": (False, "gabor_hsv"),
    "hsv_plus_gabor_rgb": (True, "gabor_rgb"),
    "hsv_plus_gabor_hsv": (True, "gabor_hsv"),
}

#: Provisional tolerances (Phase 4 replaces them). LTP values are the BICA ones;
#: Gabor values are placeholders until calibrated.
TOLERANCES = {
    "ltp": 0.50,
    "ltp_rgb": 0.23,
    "ltp_hsv": 0.23,
    "gabor": 0.30,
    "gabor_rgb": 0.30,
    "gabor_hsv": 0.30,
}

#: Phase 4 output (``scripts/phase4_calibration.py``, model names
#: ``<dataset>_<lighting>``) and the "other object" regime whose gap-optimal
#: tolerance is used: ``across_object`` (the plan's rule) or ``same_shape``.
CALIBRATED_TOLERANCES = REPO / "docs/ltp/results/phase4/tolerances.csv"
TOLERANCE_REGIME = "across_object"

TEXTURE_FEATURE_WEIGHT = 1.0
HSV_ON = "${np.array:[2, 0.5, 0.5]}"
HSV_OFF = "${np.array:[0, 0, 0]}"
BASE_SM_FEATURES = [
    "pose_vectors", "pose_fully_defined", "on_object", "object_coverage", "rgba",
    "hsv", "min_depth", "mean_depth", "principal_curvatures",
    "principal_curvatures_log", "gaussian_curvature", "mean_curvature",
    "gaussian_curvature_sc", "mean_curvature_sc",
]
LTP_CONFIG = {"texture_extraction": {"local_ternary_pattern": {
    "n_neighbors": 8, "radius": 1.0, "threshold": 5.0, "method": "uniform"}}}
GABOR_CONFIG = {"wavelengths": [4.0, 8.0, 16.0], "n_orientations": 4, "method": "fft"}

HEADER = "# GENERATED by scripts/generate_journal_configs.py -- edit the script, not this file.\n"


def calibrated_tolerances() -> dict[tuple[str, str], float]:
    """Read Phase 4's CSV, if present.

    Returns:
        ``{(<dataset>_<lighting>, feature): tolerance}``, rounded to 3 places.
    """
    if not CALIBRATED_TOLERANCES.is_file():
        return {}
    with CALIBRATED_TOLERANCES.open() as f:
        return {
            (row["model"], row["feature"]): round(
                float(row[f"{TOLERANCE_REGIME}_tolerance"]), 3
            )
            for row in csv.DictReader(f)
        }


def write(path: Path, package: str, body: dict, comment: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(body, sort_keys=False, default_flow_style=False)
    # Hydra resolver strings must stay unquoted-equivalent; safe_dump quotes them,
    # which OmegaConf still resolves, so no post-processing is needed.
    path.write_text(f"# @package {package}\n\n{HEADER}{comment}\n{text}")


def sensor_module_name(texture: str | None) -> str:
    return f"camera_surf_rgba_{texture or 'no_texture'}"


def write_sensor_modules() -> None:
    for texture in sorted({t for _, t in CONDITIONS.values()}, key=str):
        sm = {
            "_target_": "tbp.monty.frameworks.models.sensor_modules.CameraSM",
            "is_surface_sm": True,
            "sensor_module_id": "patch",
            "features": BASE_SM_FEATURES + ([texture] if texture else []),
        }
        if texture and texture.startswith("ltp"):
            sm["ltp_config"] = LTP_CONFIG
        if texture and texture.startswith("gabor"):
            sm["gabor_config"] = GABOR_CONFIG
        sm["save_raw_obs"] = False
        write(
            CONF / "monty/sensor_module/journal" / f"{sensor_module_name(texture)}.yaml",
            "experiment.config.monty_config.sensor_modules",
            {"sensor_module_0": sm, "sensor_module_1": {
                "_target_": "tbp.monty.frameworks.models.sensor_modules.Probe",
                "sensor_module_id": "view_finder", "save_raw_obs": False}},
            f"# Eval sensor module emitting texture feature: {texture or 'none'}.\n",
        )


def write_learning_modules() -> None:
    template = yaml.safe_load(
        (CONF / "monty/learning_module/evidence_1lm_nn5_dod0025.yaml").read_text())
    for condition, (hsv_on, texture) in CONDITIONS.items():
        lm = dict(template["learning_module_0"])
        weights = {"hsv": HSV_ON if hsv_on else HSV_OFF,
                   "pose_vectors": "${np.ones:3}",
                   "principal_curvatures_log": "${np.ones:2}"}
        tolerances = {"hsv": "${np.array:[0.1, 0.2, 0.2]}",
                      "principal_curvatures_log": "${np.ones:2}"}
        if texture:
            weights[texture] = TEXTURE_FEATURE_WEIGHT
            tolerances[texture] = TOLERANCES[texture]
        lm["feature_weights"] = {"patch": weights}
        lm["tolerances"] = {"patch": tolerances}
        body = {"defaults": [
            "/monty/learning_module/hypotheses_updater/burst_sampling_5nn@learning_module_0"],
            "learning_module_0": lm}
        write(CONF / "monty/learning_module/journal/main"
              / f"evidence_1lm_nn5_dod0025_{condition}.yaml",
              "experiment.config.monty_config.learning_modules", body,
              f"# Condition {condition}: center-pixel hsv {'on' if hsv_on else 'off'}, "
              f"texture feature {texture or 'none'}"
              + (f" (weight {TEXTURE_FEATURE_WEIGHT}, tolerance {TOLERANCES[texture]})"
                 if texture else "") + ".\n")


def object_names(dataset: str) -> list[str]:
    path = DATA / DATASETS[dataset] / "object_names.yaml"
    return yaml.safe_load(path.read_text())["object_names"]


def write_env_interfaces() -> None:
    for dataset in DATASETS:
        names = object_names(dataset)
        write(CONF / "env_interface/journal" / f"train_3dc_{dataset}.yaml",
              "experiment.config", {
                  "do_train": True,
                  "train_env_interface_class":
                      "${monty.class:tbp.monty.experiment.environment.OneObjectPerEpisodeInterface}",
                  "train_env_interface_args": {
                      "parent_to_child_mapping": None, "object_names": names,
                      "object_init_sampler": {
                          "_target_": "tbp.monty.frameworks.environments.object_init_samplers.Predefined",
                          "rotations": "${constants.rotations_all}"}}},
              f"# 3DC-{dataset.capitalize()} training objects ({len(names)}), 14 "
              "predefined rotations each.\n")
        write(CONF / "env_interface/journal" / f"eval_3dc_{dataset}.yaml",
              "experiment.config", {
                  "do_eval": True,
                  "eval_env_interface_class":
                      "${monty.class:tbp.monty.experiment.environment.OneObjectPerEpisodeInterface}",
                  "eval_env_interface_args": {
                      "parent_to_child_mapping": None, "object_names": names,
                      "object_init_sampler": {
                          "_target_": "tbp.monty.frameworks.environments.object_init_samplers.RandomRotation"}}},
              f"# 3DC-{dataset.capitalize()} eval objects ({len(names)}), a fresh random "
              "rotation per episode.\n")


def pretrain_name(dataset: str, lighting: str) -> str:
    return f"pretrain_3dc_{dataset}_{lighting}_all_features"


def data_path(dataset: str) -> str:
    return "${path.expanduser:${oc.env:MONTY_DATA}/" + DATASETS[dataset] + "}"


def write_experiments() -> int:
    calibrated = calibrated_tolerances()
    n_calibrated = 0
    for dataset in DATASETS:
        for lighting, environment in LIGHTINGS.items():
            name = pretrain_name(dataset, lighting)
            write(CONF / "experiment/journal" / f"{name}.yaml", "_global_", {
                "defaults": [
                    {"/monty": "graph_exp1000_e3_t3_tot2500"},
                    {"/monty/motor_system_config": "surface_curvature_informed_goal0"},
                    {"/monty/learning_module": "displacement_delta_d0001_ltp"},
                    {"/monty/sensor_module": "journal/camera_surf_rgba_all_texture"},
                    {"/monty/connectivity": "1lm_1sm"},
                    {"/environment": environment},
                    {"/env_interface": f"journal/train_3dc_{dataset}"},
                    {"/env_interface/transform": "missing_depthto3d_sensor2_semantic0"},
                    {"/logging": "silent_info_train"},
                ],
                "experiment": {
                    "_target_": "tbp.monty.frameworks.experiments.pretraining_experiments.MontySupervisedObjectPretrainingExperiment",
                    "config": {
                        "show_sensor_output": False, "max_train_steps": 1000,
                        "max_eval_steps": 500, "max_total_steps": 6000,
                        "n_train_epochs": "${constants.rotations_all_count}",
                        "n_eval_epochs": 3, "model_name_or_path": "",
                        "min_lms_match": 1, "seed": 42, "supervised_lm_ids": "all",
                        "environment": {"env_init_args": {"data_path": data_path(dataset)}},
                        "logging": {"run_name": name}}}},
                f"# Combined-feature pretraining, 3DC-{dataset.capitalize()}, {lighting} "
                "lighting: one model serves every condition.\n")
            for condition, (hsv_on, texture) in CONDITIONS.items():
                ename = f"eval_3dc_{dataset}_{lighting}_{condition}"
                tolerance = calibrated.get((f"{dataset}_{lighting}", texture))
                monty_override = {}
                tolerance_note = ""
                if tolerance is not None:
                    n_calibrated += 1
                    monty_override = {"monty_config": {"learning_modules": {
                        "learning_module_0": {"tolerances": {"patch": {
                            texture: tolerance}}}}}}
                    tolerance_note = (f"# {texture} tolerance {tolerance}: Phase 4, "
                                      f"{TOLERANCE_REGIME} regime, this model.\n")
                write(CONF / "experiment/journal" / f"{ename}.yaml", "_global_", {
                    "defaults": [
                        {"/monty": "evidencegraph_exp1000_emin_t3_tot2500"},
                        {"/monty/motor_system_config": "surface_curvature_informed_goal1"},
                        {"/monty/learning_module":
                             f"journal/main/evidence_1lm_nn5_dod0025_{condition}"},
                        {"/monty/sensor_module": f"journal/{sensor_module_name(texture)}"},
                        {"/monty/connectivity": "1lm_1sm"},
                        {"/environment": environment},
                        {"/env_interface": f"journal/eval_3dc_{dataset}"},
                        {"/env_interface/transform": "missing_depthto3d_sensor2_semantic0"},
                        {"/logging": "basic_info_evidence_eval_runs"},
                    ],
                    "experiment": {
                        "_target_": "tbp.monty.frameworks.experiments.object_recognition_experiments.MontyObjectRecognitionExperiment",
                        "config": {
                            "show_sensor_output": False, "max_train_steps": 1000,
                            "max_eval_steps": 500, "max_total_steps": 6000,
                            "n_train_epochs": 3,
                            "model_name_or_path":
                                "${constants.retextured_pretrained_dir}/"
                                f"{pretrain_name(dataset, lighting)}/pretrained/",
                            "n_eval_epochs": 5, "min_lms_match": 1, "seed": 42,
                            # Eval does not change the model; saving it would
                            # write a ~0.9 GB copy per parallel episode.
                            "save_eval_models": False,
                            "supervised_lm_ids": [],
                            "environment": {"env_init_args": {"data_path": data_path(dataset)}},
                            "logging": {"run_name": ename},
                            **monty_override}}},
                    f"# Eval, 3DC-{dataset.capitalize()}, {lighting} lighting, condition "
                    f"{condition}: center-pixel hsv {'on' if hsv_on else 'off'}, texture "
                    f"{texture or 'none'}.\n" + tolerance_note)
    return n_calibrated


def main() -> None:
    write_sensor_modules()
    write_learning_modules()
    write_env_interfaces()
    n_calibrated = write_experiments()
    n_exp = len(DATASETS) * len(LIGHTINGS) * (1 + len(CONDITIONS))
    print(f"wrote {n_exp} experiments, {len(CONDITIONS)} learning modules; "
          f"{n_calibrated} evals use Phase 4 tolerances ({TOLERANCE_REGIME})")


if __name__ == "__main__":
    main()
